export function demoHistory(
  id: number,
  now = Date.now(),
  window: HistoryWindow = "24h",
): import("./contracts").History {
  const points = (demoSamples[id] ?? []).map(([minutes, stars, forks]) => ({
    at: now + minutes * 60_000,
    stars,
    forks,
  })).filter(point => point.at >= now - historyDuration(window) && point.at <= now);
  return {
    repositoryId: id,
    window,
    fetchedAt: now,
    points,
    availability: points.length >= 2 ? "available" : "insufficient",
  };
}
